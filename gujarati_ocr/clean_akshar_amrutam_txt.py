def normalize_line(line: str) -> str:
    line = unicodedata.normalize("NFC", line)

    # Re-attach Gujarati dependent signs that OCR split with spaces.
    line = re.sub(rf"\s+([{GUJARATI_MARKS}])", r"\1", line)
    line = re.sub(r"્\s+([\u0A80-\u0AFF])", r"્\1", line)
    line = re.sub(r"([૦-૯])\s+([૦-૯])", r"\1\2", line)
    line = re.sub(r"([૦-૯])\s+([૦-૯])", r"\1\2", line)
    line = re.sub(r"([૦-૯])\s+([૦-૯])", r"\1\2", line)

    line = re.sub(r"\s+([,.:;!?%])", r"\1", line)
    line = re.sub(r"([({\[])\s+", r"\1", line)
    line = re.sub(r"\s{2,}", " ", line)
    return line.strip()


def clean_text(text: str) -> str:
    text = text.replace("\x00", "")
    lines = [normalize_line(raw) for raw in text.splitlines()]
    cleaned = "\n".join(line for line in lines if line)
    for pattern, replacement in PHRASE_REPLACEMENTS:
        cleaned = re.sub(pattern, replacement, cleaned)
    for source, target in WORD_REPLACEMENTS.items():
        cleaned = re.sub(rf"(?<![\u0A80-\u0AFF]){re.escape(source)}(?![\u0A80-\u0AFF])", target, cleaned)
    cleaned = re.sub(r"\n{3,}", "\n\n", cleaned)
    return cleaned.strip() + "\n"


def normalized_title_from_filename(path: Path) -> str:
    stem = path.stem
    _, title = stem.split(" - ", 1)
    return f"❖ {title}"


def main() -> None:
    count = 0
    for path in sorted(OUTPUT_DIR.glob("*.txt")):
        original = path.read_text(encoding="utf-8")
        cleaned = clean_text(original)
        lines = cleaned.splitlines()
        if lines:
            lines[0] = normalized_title_from_filename(path)
            filtered: list[str] = [lines[0]]
            title_tail = lines[0].removeprefix("❖ ").split(",")[-1].strip()
            for line in lines[1:]:
                stripped = line.strip()
                if re.fullmatch(r"\(સ\s*ત્ર\s*\d+\s*\)", stripped):
                    continue
                if stripped == title_tail:
                    continue
                filtered.append(line)
            lines = filtered
            cleaned = "\n".join(lines).strip() + "\n"
        path.write_text(cleaned, encoding="utf-8")
        count += 1
    print(f"Cleaned {count} files in {OUTPUT_DIR}")


if __name__ == "__main__":
    main()
